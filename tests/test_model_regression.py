"""Golden-file regression test for the real load models.

For every registered model the golden file (tests/golden/<model>.json) records what the model produced before this
test existed: its CON names and defaults, display rows, the `.dyr` record it writes (in full for the defaults, as a
digest for every preset and block), and a digest of its simulated response over a grid of voltage and frequency
events, for the defaults and for every ride-through preset. A change to any CON name, default, `.dyr` text or
simulator result fails here, naming the entries that moved.

The golden files were generated from release 1.2.1, before the load models were restructured. If a change is meant to
alter a model's behavior, regenerate them and review the diff:

    UPDATE_GOLDEN=1 uv run pytest tests/test_model_regression.py

`tests/golden/ui_export_<model>.dyr` is the full `.dyr` file the main window exports with that model selected.
"""

import dataclasses
import hashlib
import json
import os
import pathlib
import re

import pytest

from load_models import LOAD_MODELS
from presets.ridethrough import RIDE_THROUGH_PRESETS

GOLDEN = pathlib.Path(__file__).parent / "golden"
SCOPES = ("bus", "owner", "all")
VOLTAGE_EVENTS = [(duration, depth) for duration in (0.05, 0.5, 5.0) for depth in (0.0, 0.3, 0.6, 0.85, 1.15, 1.3)]
FREQUENCY_EVENTS = [(1.0, 56.0), (5.0, 58.2), (5.0, 63.0), (20.0, 64.0)]
UI_EXPORT_MODELS = ("perc1_dll", "perc1_standard", "perc2_standard", "perc2_dll")
TIMESTAMP_RE = re.compile(r"generated by PERC Studio on \S+")


def _plain(value):
    if dataclasses.is_dataclass(value):
        return _plain(dataclasses.asdict(value))
    if hasattr(value, "tolist"):
        return value.tolist()
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    if isinstance(value, float):
        return repr(value)
    return value if isinstance(value, (int, str, bool, type(None))) else repr(value)


def _digest(value) -> str:
    return hashlib.sha256(json.dumps(_plain(value), sort_keys=True).encode()).hexdigest()[:16]


def _cons_sets(model) -> dict:
    """The CON sets to exercise: the defaults, and the model's encoding of every preset for both blocks."""
    sets = {"defaults": dict(model.default_cons)}
    if model.cons_for_preset:
        for preset in RIDE_THROUGH_PRESETS.values():
            for block in ("it", "vfd"):
                sets[f"{preset.id}/{block}"] = model.cons_for_preset(preset, block)
    if model.id == "perc2_dll":  # momentary cessation is a separate simulator path
        sets.update({f"{name}+mc": {**cons, "MCFLAG": 1, "FCEASE": 0.6, "FRECON": 0.8} for name, cons in list(sets.items())})
    return sets


def _record(model, cons, scope) -> str:
    try:
        return model.build_dyr_record(0 if scope == "all" else 1234, "1", cons, scope)
    except ValueError as exc:
        return f"ERROR: {exc}"


def snapshot(model) -> dict:
    sets = _cons_sets(model)
    out = {
        "con_names": list(model.con_names),
        "default_cons": _plain(model.default_cons),
        "display_fields": _plain(model.display_fields),
        "dyr_defaults": {scope: _record(model, sets["defaults"], scope).splitlines() for scope in SCOPES},
        "cons": {name: _digest(cons) for name, cons in sets.items()},
        "dyr": {name: _digest(_record(model, cons, "bus")) for name, cons in sets.items()},
        "simulations": {},
    }
    if model.parse_dyr_record:
        text = _record(model, sets["defaults"], "bus")
        out["parsed_defaults"] = _plain(model.parse_dyr_record(text))
    for name, cons in sets.items():
        if model.simulate:
            for duration, depth in VOLTAGE_EVENTS:
                out["simulations"][f"{name}/v/{duration}/{depth}"] = _digest(model.simulate(cons, duration, depth))
        if model.simulate_frequency:
            for duration, hz in FREQUENCY_EVENTS:
                out["simulations"][f"{name}/f/{duration}/{hz}"] = _digest(model.simulate_frequency(cons, duration, hz))
    return out


def ui_export(model_id: str) -> str:
    """The `.dyr` file the main window exports with `model_id` selected for the IT block (timestamp masked)."""
    from PySide6.QtWidgets import QApplication

    from export.dyr import build_dyr_text
    from ui.main_window import MainWindow

    app = QApplication.instance() or QApplication([])
    window = MainWindow("post-commissioning")
    combo = window.pc_it_model_combo
    combo.setCurrentIndex(combo.findData(model_id))
    app.processEvents()
    text = build_dyr_text(window._state_from_post_form())
    window.close()
    return TIMESTAMP_RE.sub("generated by PERC Studio on <timestamp>", text).replace("\r\n", "\n")


def write_golden() -> None:
    GOLDEN.mkdir(exist_ok=True)
    for model in LOAD_MODELS.values():
        (GOLDEN / f"{model.id}.json").write_text(json.dumps(snapshot(model), indent=1) + "\n", encoding="utf8", newline="\n")
    for model_id in UI_EXPORT_MODELS:
        (GOLDEN / f"ui_export_{model_id}.dyr").write_text(ui_export(model_id), encoding="utf8", newline="\n")


def _moved(want, got):
    if isinstance(want, dict) and isinstance(got, dict):
        return sorted(k for k in set(want) | set(got) if want.get(k) != got.get(k))
    return [] if want == got else ["(value)"]


@pytest.mark.skipif(bool(os.environ.get("UPDATE_GOLDEN")), reason="regenerating the golden files")
@pytest.mark.parametrize("model", list(LOAD_MODELS.values()), ids=lambda m: m.id)
def test_model_matches_its_golden_file(model):
    want = json.loads((GOLDEN / f"{model.id}.json").read_text(encoding="utf8"))
    got = snapshot(model)
    assert set(got) == set(want)
    for section, expected in want.items():
        moved = _moved(expected, got[section])
        assert not moved, f"{model.id}: {section} changed: {moved[:8]}{' ...' if len(moved) > 8 else ''}"


@pytest.mark.skipif(bool(os.environ.get("UPDATE_GOLDEN")), reason="regenerating the golden files")
@pytest.mark.parametrize("model_id", UI_EXPORT_MODELS)
def test_main_window_export_matches_its_golden_file(model_id):
    want = (GOLDEN / f"ui_export_{model_id}.dyr").read_text(encoding="utf8").replace("\r\n", "\n")
    assert ui_export(model_id) == want


@pytest.mark.skipif(not os.environ.get("UPDATE_GOLDEN"), reason="set UPDATE_GOLDEN=1 to regenerate the golden files")
def test_regenerate_golden_files():
    write_golden()
